func writeFile(t *testing.T, root, rel, content string) {
	t.Helper()
	path := filepath.Join(root, filepath.FromSlash(rel))
	require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
	require.NoError(t, os.WriteFile(path, []byte(content), 0o644))
}

func TestShouldCheck(t *testing.T) {
	cases := map[string]bool{
		"cmd/ztd/main.go":                 true,
		"console/src/App.tsx":             true,
		"scripts/dev-check.sh":            true,
		"protocol/proto/ztd/v1/x.proto":   true,
		"Makefile":                        true,
		"protocol/Makefile":               true,
		"tools/legacy.py":                 false,
		"README.md":                       false,
		"vendor/github.com/x/y.go":        false,
		"console/node_modules/a/index.js": false,
		"console/dist/app.js":             false,
		"internal/static/assets/app.js":   false,
		"website/site/assets/bundle.js":   false,
		"website/lib.min.js":              false,
		"console/package-lock.json":       false,
		"internal/x/__pycache__/thing.go": false,
	}
	for rel, want := range cases {
		assert.Equal(t, want, shouldCheck(rel), rel)
	}
}

func TestFindMissing_ReportsOnlyUnheaderedFirstPartySources(t *testing.T) {
	root := t.TempDir()
	writeFile(t, root, "ok.go", header+"package ok\n")
	writeFile(t, root, "alt.ts", "// Licensed under BSL 1.1\nexport {}\n")
	writeFile(t, root, "gen.pb.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage gen\n")
	writeFile(t, root, "bad.go", "package bad\n")
	writeFile(t, root, "sub/Makefile", "all:\n")
	writeFile(t, root, "legacy.py", "print('ignored')\n")
	writeFile(t, root, ".hidden/bad.go", "package hidden\n")
	writeFile(t, root, "node_modules/x/bad.js", "module.exports = 1\n")
	writeFile(t, root, "late.sh", "#!/bin/sh\n"+repeat("echo\n", 12)+"# Business Source License\n")

	missing, err := findMissing(root)
	require.NoError(t, err)
	assert.Equal(t, []string{"bad.go", "late.sh", "sub/Makefile"}, missing)
}

func TestRun_ExitCodes(t *testing.T) {
	root := t.TempDir()
	writeFile(t, root, "ok.go", header+"package ok\n")

	var stdout, stderr bytes.Buffer
	assert.Equal(t, 0, run([]string{"-root", root}, &stdout, &stderr))
	assert.Contains(t, stdout.String(), "BSL header check OK")

	writeFile(t, root, "pkg/bad.go", "package bad\n")
	stdout.Reset()
	stderr.Reset()
	assert.Equal(t, 1, run([]string{"-root", root}, &stdout, &stderr))
	assert.Contains(t, stderr.String(), "pkg/bad.go")
}

func repeat(s string, n int) string {
	return string(bytes.Repeat([]byte(s), n))
}
