// bslheaders verifies that first-party source files carry the BSL 1.1
// license header. Generated protobuf output, vendored code, build output, and
// minified bundles are skipped.
//
//	go run ./internal/tools/bslheaders
//	go run ./internal/tools/bslheaders -root /path/to/repo
package main

import (
	"bufio"
	"flag"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// skipDirs are never descended into. Any other dot-directory is also skipped.
var skipDirs = map[string]bool{
	".git":          true,
	".ztd":          true,
	".local.dev":    true,
	".pytest_cache": true,
	".venv":         true,
	"__pycache__":   true,
	"build":         true,
	"coverage":      true,
	"dist":          true,
	"node_modules":  true,
	"vendor":        true,
}

var sourceExts = map[string]bool{
	".go":    true,
	".js":    true,
	".ts":    true,
	".tsx":   true,
	".proto": true,
	".sh":    true,
}

var specialFiles = map[string]bool{
	"Makefile": true,
}

var skipPathSubstrings = []string{
	"/site/assets/",
	"/static/assets/",
	".min.js",
	".min.css",
	"/vendor/",
	"package-lock.json",
}

var generatedPrefixes = []string{
	"// Code generated by protoc-gen-go",
	"# Code generated by protoc",
	"# Generated by the protocol buffer compiler",
}

const (
	generatedHeadLines = 10
	headerHeadLines    = 12
)

func main() {
	os.Exit(run(os.Args[1:], os.Stdout, os.Stderr))
}

func run(args []string, stdout, stderr io.Writer) int {
	flags := flag.NewFlagSet("bslheaders", flag.ContinueOnError)
	flags.SetOutput(stderr)
	root := flags.String("root", "", "repository root to scan (default: nearest go.mod above the working directory)")
	if err := flags.Parse(args); err != nil {
		return 2
	}
	scanRoot := *root
	if scanRoot == "" {
		found, err := findRepoRoot()
		if err != nil {
			fmt.Fprintf(stderr, "bslheaders: %v\n", err)
			return 1
		}
		scanRoot = found
	}
	abs, err := filepath.Abs(scanRoot)
	if err != nil {
		fmt.Fprintf(stderr, "bslheaders: resolve root: %v\n", err)
		return 1
	}
	missing, err := findMissing(abs)
	if err != nil {
		fmt.Fprintf(stderr, "bslheaders: %v\n", err)
		return 1
	}
	if len(missing) > 0 {
		fmt.Fprintln(stderr, "ERROR: first-party source files missing BSL 1.1 headers:")
		for _, rel := range missing {
			fmt.Fprintf(stderr, "  %s\n", rel)
		}
		return 1
	}
	fmt.Fprintln(stdout, "BSL header check OK")
	return 0
}

// findMissing returns slash-separated paths, relative to root and sorted, of
// checked source files that lack a BSL header.
func findMissing(root string) ([]string, error) {
	var missing []string
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if d.IsDir() {
			if path != root && (skipDirs[d.Name()] || strings.HasPrefix(d.Name(), ".")) {
				return filepath.SkipDir
			}
			return nil
		}
		if !d.Type().IsRegular() {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return fmt.Errorf("relativize %s: %w", path, err)
		}
		rel = filepath.ToSlash(rel)
		if !shouldCheck(rel) {
			return nil
		}
		head, err := readHead(path, headerHeadLines)
		if err != nil {
			return err
		}
		if isGenerated(head) || hasBSLHeader(head) {
			return nil
		}
		missing = append(missing, rel)
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("scan %s: %w", root, err)
	}
	sort.Strings(missing)
	return missing, nil
}

// shouldCheck reports whether the slash-separated repo-relative path is a
// first-party source file that must carry a header.
func shouldCheck(rel string) bool {
	for _, part := range strings.Split(rel, "/") {
		if skipDirs[part] {
			return false
		}
	}
	rendered := "/" + rel
	for _, substr := range skipPathSubstrings {
		if strings.Contains(rendered, substr) {
			return false
		}
	}
	name := filepath.Base(rel)
	if specialFiles[name] {
		return true
	}
	return sourceExts[filepath.Ext(name)]
}

func readHead(path string, n int) ([]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, fmt.Errorf("open %s: %w", path, err)
	}
	defer f.Close()
	scanner := bufio.NewScanner(f)
	scanner.Buffer(make([]byte, 0, 64*1024), 1024*1024)
	lines := make([]string, 0, n)
	for len(lines) < n && scanner.Scan() {
		lines = append(lines, scanner.Text())
	}
	if err := scanner.Err(); err != nil && err != bufio.ErrTooLong {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}
	return lines, nil
}

func isGenerated(head []string) bool {
	text := strings.Join(head[:min(len(head), generatedHeadLines)], "\n")
	for _, prefix := range generatedPrefixes {
		if strings.Contains(text, prefix) {
			return true
		}
	}
	return false
}

func hasBSLHeader(head []string) bool {
	text := strings.Join(head[:min(len(head), headerHeadLines)], "\n")
	return strings.Contains(text, "Business Source License") || strings.Contains(text, "BSL 1.1")
}

func findRepoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found above working directory")
		}
		dir = parent
	}
}
