package main

import (
	"bytes"
	"fmt"
	"strings"
)

// renderNotices produces the THIRD_PARTY_NOTICES.md body. Output depends only
// on its inputs, so identical inputs always produce identical bytes.
func renderNotices(goMods []GoModule, npmPkgs []NPMPackage) []byte {
	var b bytes.Buffer
	fmt.Fprintln(&b, "# Third-Party Notices")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "This file lists third-party software distributed inside the ztd binary, with the")
	fmt.Fprintln(&b, "license and notice text shipped by each dependency.")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "Generated by `make third-party-notices`. Do not edit by hand.")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "- Go modules (from `vendor/modules.txt`): %d\n", len(goMods))
	fmt.Fprintf(&b, "- npm packages (production, from `console/` and `evaluation-explorer/`): %d\n", len(npmPkgs))
	fmt.Fprintln(&b)

	fmt.Fprintln(&b, "## Go modules")
	fmt.Fprintln(&b)
	for _, m := range goMods {
		heading := m.Path
		if m.Version != "" {
			heading += " " + m.Version
		}
		fmt.Fprintf(&b, "### %s\n\n", heading)
		if m.Replacement != "" {
			fmt.Fprintf(&b, "Replaced by `%s`.\n\n", m.Replacement)
		}
		if len(m.Files) == 0 {
			fmt.Fprintln(&b, "No license file was found in the vendored module root. See the module source for its license terms.")
			fmt.Fprintln(&b)
			continue
		}
		for _, f := range m.Files {
			writeLicenseBlock(&b, f)
		}
	}

	fmt.Fprintln(&b, "## npm packages")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "Production dependencies of the embedded frontends. Where `node_modules` was not installed")
	fmt.Fprintln(&b, "at generation time, only the name, version, and license identifier are recorded.")
	fmt.Fprintln(&b)
	for _, p := range npmPkgs {
		fmt.Fprintf(&b, "### %s %s\n\n", p.Name, p.Version)
		fmt.Fprintf(&b, "- License: %s\n", p.License)
		fmt.Fprintf(&b, "- Used by: %s\n\n", strings.Join(p.Apps, ", "))
		switch {
		case len(p.Files) > 0:
			for _, f := range p.Files {
				writeLicenseBlock(&b, f)
			}
		case p.HasNodeModules:
			fmt.Fprintln(&b, "No license file was found in the installed package. See the package source for its license terms.")
			fmt.Fprintln(&b)
		}
	}
	return b.Bytes()
}

// writeLicenseBlock emits one license or notice file as a fenced block. The
// fence is longer than any backtick run in the text so the block cannot close
// early.
func writeLicenseBlock(b *bytes.Buffer, f LicenseFile) {
	fence := strings.Repeat("`", max(3, longestBacktickRun(f.Text)+1))
	text := strings.TrimRight(f.Text, "\n")
	fmt.Fprintf(b, "#### %s\n\n%stext\n%s\n%s\n\n", f.Name, fence, text, fence)
}

func longestBacktickRun(s string) int {
	longest, run := 0, 0
	for _, r := range s {
		if r == '`' {
			run++
			longest = max(longest, run)
			continue
		}
		run = 0
	}
	return longest
}
